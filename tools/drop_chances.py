"""Writes Wayward/Data/DropChances.lua: how often each creature (or object)
drops the items quests ask for, in percent, and how many each quest asks for.

The chances are pfQuest's (MIT, github.com/shagu/pfQuest), read from the
Polestar quest database pack, which carries them per item. Only items that
some quest asks you to collect are kept.

    py -3 -I tools/drop_chances.py "<AddOns>/Polestar_QuestDB"
"""

import pathlib
import re
import sys

RECORD = re.compile(r"^(\d+)\t'(.*)$")


def records(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        m = RECORD.match(line)
        if m:
            yield int(m.group(1)), m.group(2).split(";")


def objectives(quests):
    """What quests ask for: objectives are {kind,id,count,... (kind 1: kill
    a creature, 2: collect an item). Returns the item IDs asked for and
    { questID: [(kind, id, count), ...] }."""
    items, counts = set(), {}
    for quest_id, fields in records(quests):
        if len(fields) < 12 or not fields[11].startswith("{"):
            continue
        parts = fields[11][1:].split(",")
        for i in range(0, len(parts) - 2, 3):
            kind, oid, count = parts[i:i + 3]
            if kind in ("1", "2") and oid.isdigit() and count.isdigit() and int(count) > 0:
                counts.setdefault(quest_id, []).append((kind, int(oid), int(count)))
                if kind == "2":
                    items.add(int(oid))
    return items, counts


def drop_lists(fields):
    """name, npc count, (npc, chance)..., object count, (object, chance)..."""
    out, i = {"n": [], "o": []}, 1
    for key in ("n", "o"):
        if i >= len(fields) or not fields[i].isdigit():
            break
        count = int(fields[i])
        i += 1
        for _ in range(count):
            if i + 1 >= len(fields):
                break
            source, chance = fields[i], fields[i + 1]
            i += 2
            try:
                pct = float(chance)
            except ValueError:
                continue
            if source.isdigit() and pct > 0:
                out[key].append((int(source), pct))
    return out


def fmt(pct):
    return ("%.2f" % pct).rstrip("0").rstrip(".")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pack = pathlib.Path(sys.argv[1])
    wanted, counts = objectives(pack / "Quests.lua")
    rows = []
    for item_id, fields in records(pack / "Items.lua"):
        if item_id not in wanted:
            continue
        lists = drop_lists(fields)
        parts = []
        for key in ("n", "o"):
            if lists[key]:
                flat = ",".join("%d,%s" % (source, fmt(pct)) for source, pct in lists[key])
                parts.append("%s={%s}" % (key, flat))
        if parts:
            rows.append("[%d]={%s}," % (item_id, ",".join(parts)))
    count_rows = []
    for quest_id in sorted(counts):
        by = {"1": [], "2": []}
        for kind, oid, count in counts[quest_id]:
            by[kind].append("[%d]=%d" % (oid, count))
        parts = []
        if by["1"]:
            parts.append("npc={%s}" % ",".join(by["1"]))
        if by["2"]:
            parts.append("item={%s}" % ",".join(by["2"]))
        count_rows.append("[%d]={%s}," % (quest_id, ",".join(parts)))
    out = pathlib.Path(__file__).resolve().parent.parent / "Wayward" / "Data" / "DropChances.lua"
    out.write_text(
        "local _, ns = ...\n\n"
        "-- GENERATED by tools/drop_chances.py; do not edit by hand.\n"
        "-- How often each creature (n) or object (o) drops an item a quest asks\n"
        "-- for: { [itemID] = { n = { npcID, percent, ... }, o = { objectID, percent, ... } } }.\n"
        "-- Chances from pfQuest (MIT, github.com/shagu/pfQuest, see LICENSES/pfQuest.txt),\n"
        "-- as carried by the Polestar quest database pack. Classic-era samples: Forever\n"
        "-- may differ, and a chance is what to expect, not a promise.\n"
        "ns.DropChances = {\n" + "\n".join(rows) + "\n}\n\n"
        "-- How many each quest asks for: { [questID] = { npc = { [npcID] = kills },\n"
        "-- item = { [itemID] = count } } }, for quests not in your log yet (the\n"
        "-- log says what's left of those that are).\n"
        "ns.ObjectiveCounts = {\n" + "\n".join(count_rows) + "\n}\n",
        encoding="utf-8", newline="\n")
    print("%d items, %d quests written to %s" % (len(rows), len(count_rows), out))


if __name__ == "__main__":
    main()
