#!/usr/bin/env python3
"""Every piece of player-facing text in the addon, as one Markdown file to
audit: docs/copy.md (run from the repository root: python3 tools/extract_copy.py).

It reads the Lua files the TOC lists and the TOC's own Notes line, pulls out
every string literal, drops the ones that aren't copy (texture and font
paths, event and key names, format strings with nothing but placeholders,
identifiers, colour codes) and groups the rest by file with the line number,
so a line in the output leads straight to the place to edit. Strings built
from several pieces (`"a " .. x .. " b"`) appear as their pieces, one line
each, in order.
"""
import re, sys, os, io

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON = os.path.join(ROOT, "Wayward")
OUT = os.path.join(ROOT, "docs", "copy.md")

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\'')
COMMENT = re.compile(r'--.*$')

def is_copy(s):
    t = s.strip()
    if len(t) < 2:
        return False
    if t.startswith("Interface\\") or t.startswith("Fonts\\") or t.startswith("|T"):
        return False
    if re.fullmatch(r"[A-Z0-9_]+", t):              # EVENT_NAMES, KEYS
        return False
    if re.fullmatch(r"[a-z][A-Za-z0-9_]*", t):      # identifiers, keys
        return False
    if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*\.[A-Za-z0-9_.]+", t):  # Module.Function
        return False
    if re.fullmatch(r"[^A-Za-z]*", t):              # punctuation, numbers, "%d", "|r"
        return False
    if re.fullmatch(r"\|c[0-9a-fA-F]{8}", t):
        return False
    if re.fullmatch(r"\^?[%\[\]()\.\-+*?$]+.*", t) and " " not in t and not t[0].isalpha():
        return False
    if re.fullmatch(r"[A-Z][a-z]+", t) and t in {"Frame", "Button", "CheckButton", "EditBox", "StatusBar", "Texture"}:
        return False
    if re.fullmatch(r"(TOP|BOTTOM|LEFT|RIGHT|CENTER|TOPLEFT|TOPRIGHT|BOTTOMLEFT|BOTTOMRIGHT|OVERLAY|ARTWORK|"
                    r"BACKGROUND|BORDER|HIGH|MEDIUM|LOW|DIALOG|ADD|BLEND|ANCHOR_[A-Z]+|OnUpdate|OnClick|OnEnter|"
                    r"OnLeave|OnShow|OnHide|OnEvent|OnDragStart|OnDragStop|OnMouseUp|OnMouseDown|OnMouseWheel|"
                    r"OnTextChanged|OnEnterPressed|OnEscapePressed|LeftButton|RightButton|LeftButtonUp|RightButtonUp|"
                    r"AnyUp|AnyDown|player|npc|target|mouseover)", t):
        return False
    if t.endswith("Template") or t.endswith("Mixin"):
        return False
    if t.startswith("GameFont") or t.startswith("UIPanel") or t.startswith("Blizzard"):
        return False
    if re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)+", t):   # atlas names
        return False
    if "%x" in t or "(%d+)" in t or "(%S" in t or "(.-)" in t or t.startswith("^") or t.endswith("$"):
        return False                                 # Lua patterns
    if re.fullmatch(r"(\\n|\\t|\|r|\|c[0-9a-fA-F]{8}|[%\s·,:;.()\[\]|-]|%[sd])*", t):
        return False                                 # only placeholders, colour codes and punctuation
    if t.startswith("Wayward") and " " not in t:   # frame names, globals
        return False
    return True

def files():
    toc = os.path.join(ADDON, "Wayward.toc")
    notes = None
    out = []
    for line in io.open(toc, encoding="utf-8"):
        line = line.rstrip("\r\n")
        if line.startswith("## Notes:"):
            notes = line.split(":", 1)[1].strip()
        elif line and not line.startswith("#"):
            out.append(line.replace("\\", "/"))
    return notes, out

def strings_in(path):
    found = []
    for n, line in enumerate(io.open(path, encoding="utf-8"), 1):
        code = COMMENT.sub("", line) if not line.lstrip().startswith("--") else ""
        for m in STRING.finditer(code):
            s = m.group(1) if m.group(1) is not None else m.group(2)
            if is_copy(s):
                found.append((n, s))
    return found

def main():
    notes, lua = files()
    out = ["# Wayward copy", "",
           "Every player-facing string in the addon, by file and line, for auditing. "
           "Generated by `tools/extract_copy.py`; edit the Lua file the line points to, then run it again. "
           "A sentence built from several pieces appears as its pieces, in order. "
           "`%s` and `%d` are filled in at run time; `|cffRRGGBB` ... `|r` colours a stretch of text.", ""]
    total = 0
    if notes:
        out += ["## Wayward.toc", "", "- 3: " + notes.replace("|", "\\|"), ""]
        total += 1
    for rel in lua:
        path = os.path.join(ADDON, rel)
        if rel.startswith("Data/") and rel != "Data/Seed.lua":
            continue  # data tables, not copy
        found = strings_in(path)
        if not found:
            continue
        out.append("## " + rel)
        out.append("")
        for n, s in found:
            out.append("- %d: %s" % (n, s.replace("|", "\\|")))
            total += 1
        out.append("")
    io.open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print("%s: %d strings from %d files" % (os.path.relpath(OUT, ROOT), total, len(lua)))

if __name__ == "__main__":
    main()
